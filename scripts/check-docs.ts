/**
 * Keeps the documentation honest. Fails when
 *
 * 1. the results section of README.md differs from the summary in
 *    docs/results.md, which only `npm run report` writes;
 * 2. README.md states a measured-looking number (a decimal or a power of ten)
 *    anywhere else, outside code;
 * 3. a tracked file uses a term from the list below. They describe physics
 *    this project does not do, and must not creep into its claims.
 *
 * Usage: npm run docs:check
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- results:start (generated by npm run report; do not edit) -->';
const END = '<!-- results:end -->';
const FORBIDDEN = [
  'lorentzian',
  'minkowski',
  'spacetime',
  'space-time',
  'relativity',
  'gravitational',
  'gravity',
  'schwarzschild',
  'black hole',
  'regge',
  'quantum',
  'symplectic',
  'verlet',
  'hamiltonian monte carlo',
  'metropolis',
  'pachner',
];
const SELF = 'scripts/check-docs.ts';

const problems: string[] = [];
const read = (path: string) => readFileSync(join(root, path), 'utf8');

function block(text: string, name: string): string {
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    problems.push(`${name}: results markers missing`);
    return '';
  }
  return text.slice(start + START.length, end).trim();
}

const readme = read('README.md');
const summary = block(readme, 'README.md');
if (summary === '') problems.push('README.md: the results section is empty; run `npm run report`');
if (summary !== block(read('docs/results.md'), 'docs/results.md')) {
  problems.push(
    'README.md: the results section differs from docs/results.md; run `npm run report`',
  );
}

// Outside the generated block and outside code, the README may count things
// (integers) but not quote measurements.
const prose = (readme.slice(0, readme.indexOf(START)) + readme.slice(readme.indexOf(END)))
  .replace(/```[\s\S]*?```/g, '')
  .replace(/`[^`]*`/g, '')
  .replace(/\]\([^)]*\)/g, ']');
for (const match of prose.matchAll(/\d+\.\d+(?:e[-+]?\d+)?|\d+e[-+]?\d+/gi)) {
  // Version numbers of the runtimes and the licence are not measurements.
  const context = prose.slice(Math.max(0, match.index - 12), match.index);
  if (/(Node|Python|,|or) $|Apache-$/.test(context)) continue;
  problems.push(`README.md: "${match[0]}" is a number outside the generated results section`);
}

const tracked = execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' })
  .split('\n')
  .filter((path) => /\.(ts|tsx|py|md|json|html|css|yml|toml|txt|cff)$/.test(path) && path !== SELF)
  .filter((path) => path !== 'package-lock.json');
for (const path of tracked) {
  const text = read(path).toLowerCase();
  for (const term of FORBIDDEN) {
    if (text.includes(term)) problems.push(`${path}: contains "${term}"`);
  }
}

if (problems.length > 0) {
  console.error(problems.join('\n'));
  process.exit(1);
}
console.log(`docs check passed: results in sync, ${tracked.length} files free of excluded claims`);
