const maxOf = (values: Iterable<number>) => {
  let worst = 0;
  for (const x of values) if (!Number.isNaN(x)) worst = Math.max(worst, Math.abs(x));
  return worst;
};

// --- Gauss–Bonnet -----------------------------------------------------------

function gaussBonnet() {
  const random = mulberry32(2026);
  const between = (a: number, b: number) => a + (b - a) * random();
  let worst = 0;
  let meshes = 0;
  const check = (mesh: TriangleMesh, lengths: Float64Array) => {
    const flipped = intrinsicDelaunay(mesh, lengths);
    for (const [m, l] of [
      [mesh, lengths],
      [flipped.mesh, flipped.lengths],
    ] as const) {
      const residual = gaussBonnetResidual(m, vertexCurvature(m, cornerAngles(m, l)));
      worst = Math.max(worst, Math.abs(residual));
      meshes++;
    }
  };
  for (let k = 0; k < 60; k++) {
    const grid = {
      resolution: 2 + Math.floor(random() * 22),
      jitter: between(0, 0.2),
      seed: Math.floor(random() * 1e9),
    };
    const surfaces: Surface[] = [
      plane(grid),
      gaussianBump({ ...grid, height: between(-2, 2), width: between(0.1, 2) }),
      saddle({ ...grid, bend: between(-2, 2) }),
      sphericalCap({ ...grid, radius: between(1.5, 20) }),
      cone({
        deficit: between(0.01, 6.2),
        rings: 1 + Math.floor(random() * 12),
        sectors: 3 + Math.floor(random() * 24),
      }),
    ];
    for (const s of surfaces) check(s.mesh, s.lengths);
    const closed = [
      ellipsoid(3 + (k % 8), 6 + (k % 9), [between(0.5, 2), between(0.5, 2), between(0.5, 2)]),
      torus(between(1.5, 3), between(0.3, 1), 6 + (k % 14), 4 + (k % 9)),
    ];
    for (const s of closed) check(s.mesh, edgeLengthsFromPositions(s.mesh, s.positions));
  }
  return { meshes, worst };
}

// --- Curvature --------------------------------------------------------------

function curvatureError(jitter: number, resolution: number): number {
  const s = gaussianBump({ resolution, jitter, seed: 1, height: 0.6, width: 0.45 });
  if (s.exact.kind !== 'pointwise') throw new Error('expected pointwise curvature');
  const defect = vertexCurvature(s.mesh, cornerAngles(s.mesh, s.lengths));
  const k = gaussianCurvature(s.mesh, defect, vertexAreas(s.mesh, s.lengths, 'mixed'));
  const exact = s.exact.gaussian;
  return maxOf(Array.from(k, (x, v) => x - exact[v]));
}

function coneApex() {
  let worst = 0;
  for (const deficit of [0.5, 1.2, 3, 5]) {
    const s = cone({ deficit, rings: 14, sectors: 28 });
    const defect = vertexCurvature(s.mesh, cornerAngles(s.mesh, s.lengths));
    worst = Math.max(worst, Math.abs(defect[0] - deficit));
  }
  return worst;
}

// --- Intrinsic Delaunay -----------------------------------------------------

function delaunaySweep() {
  const random = mulberry32(78);
  const runs = 3000;
  let short = 0;
  let nonSimplicial = 0;
  let flips = 0;
  let curvatureChange = 0;
  for (let i = 0; i < runs; i++) {
    const s = gaussianBump({
      resolution: 1 + Math.floor(random() * 14),
      jitter: 0.2 * random(),
      seed: Math.floor(random() * 1e9),
      height: -2 + 4 * random(),
      width: 0.1 + 1.9 * random(),
    });
    const d = intrinsicDelaunay(s.mesh, s.lengths);
    flips += d.flips;
    if (nonDelaunayEdges(d.mesh, d.lengths).length > 0) short++;
    const pairs = new Set<string>();
    for (let e = 0; e < d.mesh.edgeCount; e++) {
      const [a, b] = d.mesh.edgeVertices(e);
      pairs.add(a < b ? `${a},${b}` : `${b},${a}`);
    }
    // Fewer distinct vertex pairs than edges means a parallel edge; a loop joins a vertex to itself.
    const loops = Array.from({ length: d.mesh.edgeCount }, (_, e) => d.mesh.edgeVertices(e)).some(
      ([a, b]) => a === b,
    );
    if (pairs.size < d.mesh.edgeCount || loops) nonSimplicial++;
    const before = vertexCurvature(s.mesh, cornerAngles(s.mesh, s.lengths));
    const after = vertexCurvature(d.mesh, cornerAngles(d.mesh, d.lengths));
    curvatureChange = Math.max(curvatureChange, maxOf(Array.from(before, (x, v) => x - after[v])));
  }
  return { runs, short, nonSimplicial, flips, curvatureChange };
}

// --- Spectrum ---------------------------------------------------------------

/** Relative errors of λ1..λ10 on the unit square (the generators' square, scaled by 1/2). */
function squareEigenvalueErrors(resolution: number): number[] {
  const exact = [1, 1, 2, 4, 4, 5, 5, 8, 9, 9].map((k) => k * Math.PI ** 2);
  const s = plane({ resolution });
  const lengths = s.lengths.map((l) => l / 2);
  const { values } = laplacianSpectrum(
    cotanLaplacian(s.mesh, lengths),
    vertexAreas(s.mesh, lengths, 'barycentric'),
  );
  return exact.map((e, k) => Math.abs(values[k + 1] - e) / e);
}

function eigenResidual(n: number) {
  const random = mulberry32(n);
  const a = new Float64Array(n * n);
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) a[i * n + j] = a[j * n + i] = random() - 0.5;
  }
  const [{ values, vectors }, ms] = timed(() => symmetricEigen(a, n));
  let residual = 0;
  for (let k = 0; k < n; k += Math.max(1, Math.floor(n / 25))) {
    for (let i = 0; i < n; i++) {
      let sum = 0;
      for (let j = 0; j < n; j++) sum += a[i * n + j] * vectors[k * n + j];
      residual = Math.max(residual, Math.abs(sum - values[k] * vectors[k * n + i]));
    }
  }
  return { residual, ms };
}

// --- Heat-method distance ---------------------------------------------------

const centre = (n: number) => (n / 2) * (n + 1) + n / 2;

function greatCircle(p: ArrayLike<number>, q: ArrayLike<number>, radius: number): number {
  const cross = Math.hypot(
    p[1] * q[2] - p[2] * q[1],
    p[2] * q[0] - p[0] * q[2],
    p[0] * q[1] - p[1] * q[0],
  );
  return radius * Math.atan2(cross, p[0] * q[0] + p[1] * q[1] + p[2] * q[2]);
}

function distanceErrors(distance: Float64Array, exact: (v: number) => number) {
  const errors = Array.from(distance, (d, v) => Math.abs(d - exact(v)));
  return { max: Math.max(...errors), mean: errors.reduce((a, b) => a + b) / errors.length };
}

/** Cone of deficit 2. `fromApex` or from a vertex half-way out; exact distance by unfolding the sector. */
function coneDistance(rings: number, fromApex: boolean) {
  const sectors = 3 * rings;
  const deficit = 2;
  const s = cone({ deficit, rings, sectors });
  const sector = 2 * Math.PI - deficit;
  const polar = (v: number) =>
    v === 0
      ? { radius: 0, angle: 0 }
      : {
          radius: Math.floor((v - 1) / sectors + 1) / rings,
          angle: (((v - 1) % sectors) * sector) / sectors,
        };
  const source = fromApex ? 0 : 1 + (rings / 2 - 1) * sectors;
  const from = polar(source);
  const d = new HeatMethod(s.mesh, s.lengths).distance([source]);
  return distanceErrors(d, (v) => {
    const to = polar(v);
    const turn = Math.abs(to.angle - from.angle);
    const between = Math.min(turn, sector - turn);
    // Straight across the unfolded sector, or through the apex when the angle exceeds π.
    return between < Math.PI
      ? Math.sqrt(
          from.radius ** 2 + to.radius ** 2 - 2 * from.radius * to.radius * Math.cos(between),
        )
      : from.radius + to.radius;
  });
}

/** Unit sphere, from a pole or from a vertex on the equator. */
function sphereDistance(rings: number, fromPole: boolean) {
  const s = ellipsoid(rings, 2 * rings, [1, 1, 1]);
  const point = (v: number) => s.positions.subarray(3 * v, 3 * v + 3);
  const source = fromPole ? 0 : 1 + (rings / 2 - 1) * 2 * rings;
  const d = new HeatMethod(s.mesh, edgeLengthsFromPositions(s.mesh, s.positions)).distance([
    source,
  ]);
  return {
    vertices: s.mesh.vertexCount,
    ...distanceErrors(d, (v) => greatCircle(point(v), point(source), 1)),
  };
}

function flatDistance(n: number) {
  const s = plane({ resolution: n });
  const origin = s.positions.subarray(3 * centre(n), 3 * centre(n) + 2);
  const d = new HeatMethod(s.mesh, s.lengths).distance([centre(n)]);
  return distanceErrors(d, (v) =>
    Math.hypot(s.positions[3 * v] - origin[0], s.positions[3 * v + 1] - origin[1]),
  );
}

function capDistance(n: number) {
  const radius = 1.6;
  const s = sphericalCap({ resolution: n, radius });
  const point = (v: number) => [
    s.positions[3 * v],
    s.positions[3 * v + 1],
    s.positions[3 * v + 2] + radius,
  ];
  const exact = (v: number) => greatCircle(point(v), point(centre(n)), radius);
  const flipped = intrinsicDelaunay(s.mesh, s.lengths);
  return {
    flips: flipped.flips,
    raw: distanceErrors(new HeatMethod(s.mesh, s.lengths).distance([centre(n)]), exact).max,
    flipped: distanceErrors(
      new HeatMethod(flipped.mesh, flipped.lengths).distance([centre(n)]),
      exact,
    ).max,
  };
}

function heatMatrix(n: number): { matrix: CsrMatrix; vertices: number } {
  const s = plane({ resolution: n });
  const mass = vertexAreas(s.mesh, s.lengths, 'barycentric');
  const t = (2 / n) ** 2;
  const rows: number[] = [];
  const cols: number[] = [];
  const values: number[] = [];
  for (const [i, j, x] of cotanLaplacian(s.mesh, s.lengths).entries()) {
    rows.push(i);
    cols.push(j);
    values.push(t * x + (i === j ? mass[i] : 0));
  }
  const vertices = s.mesh.vertexCount;
  return { matrix: CsrMatrix.fromTriplets(vertices, vertices, rows, cols, values), vertices };
}

function farField() {
  const { matrix, vertices } = heatMatrix(64);
  const delta = new Float64Array(vertices);
  delta[0] = 1;
  const direct = SparseCholesky.factor(matrix).solve(delta);
  const iterative = conjugateGradient(matrix, delta, { tolerance: 1e-15 });
  return {
    vertices,
    smallest: Math.min(...direct),
    directNonPositive: direct.filter((x) => !(x > 0)).length,
    iterations: iterative.iterations,
    iterativeNonPositive: iterative.x.filter((x) => !(x > 0)).length,
  };
}

